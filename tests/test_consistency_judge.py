"""The per-source consistency judge: the model gives a stance per source, code decides.

Its purpose is one specific failure (eval/results/consistency-v2-*.md, z4 and z6): a config value
that agrees with the design used to outvote code that disagrees.
"""

import json

import pytest

from app.agent.consistency import JUDGE_PER_SOURCE_SYSTEM, decide_from_stances

D, C = {"D1", "D2"}, {"C1", "C2", "C3"}


def stances(design=(), implementation=(), explanation="Because [D1] and [C1]."):
    return json.dumps(
        {
            "design": [{"ref": r, "stance": s} for r, s in design],
            "implementation": [{"ref": r, "stance": s, "evidence": "x"} for r, s in implementation],
            "explanation": explanation,
        }
    )


def decide(**kwargs):
    return decide_from_stances(stances(**kwargs), D, C)


def test_agreeing_config_cannot_hide_code_that_contradicts() -> None:
    """The v2 failure: C1 is the config (agrees), C2 is the code (differs)."""
    f = decide(
        design=[("D1", "states")],
        implementation=[("C1", "supports"), ("C2", "contradicts")],
    )
    assert f.verdict == "potential_discrepancy"
    assert f.implementation_refs == ["C2"]  # cites the source that actually disagrees
    assert f.design_refs == ["D1"]


def test_all_supporting_sources_are_consistent() -> None:
    f = decide(design=[("D1", "states")], implementation=[("C1", "supports"), ("C2", "supports")])
    assert (f.verdict, f.design_refs, f.implementation_refs) == (
        "consistent",
        ["D1"],
        ["C1", "C2"],
    )


def test_a_design_that_contradicts_supporting_code_is_a_discrepancy() -> None:
    f = decide(design=[("D1", "contradicts")], implementation=[("C1", "supports")])
    assert f.verdict == "potential_discrepancy"
    assert (f.design_refs, f.implementation_refs) == (["D1"], ["C1"])


@pytest.mark.parametrize(
    ("design", "implementation"),
    [
        ([("D1", "states")], [("C1", "unrelated"), ("C2", "unrelated")]),  # nothing decisive
        ([("D1", "unrelated")], [("C1", "supports")]),  # the design never states it
        ([("D1", "unrelated")], [("C1", "contradicts")]),  # no design side to compare with
        ([], [("C1", "supports")]),
        ([("D1", "states")], []),
    ],
)
def test_without_a_decisive_pair_the_answer_is_insufficient_evidence(design, implementation):
    f = decide(design=design, implementation=implementation)
    assert f.verdict == "insufficient_evidence"
    assert f.downgrade_reason == "no_decisive_stance"


@pytest.mark.parametrize(
    "raw", ["not json", "[]", "{}", json.dumps({"design": "x", "implementation": 5})]
)
def test_unusable_output_is_downgraded_never_trusted(raw: str) -> None:
    f = decide_from_stances(raw, D, C)
    assert f.verdict == "insufficient_evidence" and f.downgrade_reason == "model_output_invalid"


def test_invented_refs_and_odd_stance_words_cannot_create_a_verdict() -> None:
    f = decide_from_stances(
        stances(
            design=[("D9", "states"), ("D1", "totally agrees")],  # D9 does not exist
            implementation=[("C7", "contradicts"), ("C1", "supports")],
        ),
        D,
        C,
    )
    # D1's stance word is not allowed so it counts as unrelated; C7 is ignored.
    assert f.verdict == "insufficient_evidence"


def test_the_first_stance_for_a_ref_wins_and_a_missing_explanation_gets_a_fallback() -> None:
    f = decide_from_stances(
        stances(
            design=[("D1", "states"), ("D1", "contradicts")],
            implementation=[("C1", "contradicts"), ("C1", "supports")],
            explanation="",
        ),
        D,
        C,
    )
    assert f.verdict == "potential_discrepancy"
    assert "C1" in f.explanation  # generated by code, not taken from the model


def test_the_prompt_tells_the_model_not_to_let_one_source_cancel_another() -> None:
    assert "NEVER cancels" in JUDGE_PER_SOURCE_SYSTEM
    assert "the code source" in JUDGE_PER_SOURCE_SYSTEM  # the worked config-vs-code example
